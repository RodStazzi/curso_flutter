void main() {
  //String
  final String verdura = 'lechuga';
  print(verdura);

  //Int
  final int cantidad = 5;
  print(cantidad);

  //double
  final double precio = 0.80;
  print(precio);

  //booleano
  final bool existe = true;
  print(existe);

  final tienda = [verdura, cantidad, precio, existe];
  print(tienda);

  final List<String> productos = [verdura, 'yogurt', 'frutilla'];
  print(productos);
}